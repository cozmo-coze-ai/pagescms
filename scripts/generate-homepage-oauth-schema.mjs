// Generate only the homepage provider's tables from the pinned library.
// This reads no environment credentials and never opens a database connection.
import { oauthProvider } from "@better-auth/oauth-provider";
import { jwt } from "better-auth/plugins";
import { writeFileSync } from "node:fs";

const models = { ...oauthProvider({ loginPage: "/login", consentPage: "/consent" }).schema, ...jwt().schema };
const snake = (name) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const names = Object.fromEntries(Object.keys(models).map((name) => [name, name === "jwks" ? "homepageOauthJwks" : `homepage${name[0].toUpperCase()}${name.slice(1)}`]));
const tableNames = Object.fromEntries(Object.keys(models).map((name) => [name, `cms_homepage_${name === "jwks" ? "oauth_jwks" : snake(name)}`]));
const refs = { user: "userTable", session: "sessionTable", ...names };
let output = '// Generated by scripts/generate-homepage-oauth-schema.mjs. Do not edit by hand.\nimport { pgTable, text, boolean, timestamp, jsonb, integer, index } from "drizzle-orm/pg-core";\nimport { userTable, sessionTable } from "./schema.ts";\n\n';
for (const [model, { fields }] of Object.entries(models)) {
  output += `export const ${names[model]} = pgTable(${JSON.stringify(tableNames[model])}, {\n  id: text("id").primaryKey(),\n`;
  for (const [name, field] of Object.entries(fields)) {
    const type = { string: "text", boolean: "boolean", date: "timestamp", number: "integer", json: "jsonb", "string[]": "text" }[field.type];
    if (!type) throw new Error(`Unsupported schema field ${model}.${name}: ${field.type}`);
    let expr = `${type}(${JSON.stringify(snake(name))})${field.type === "string[]" ? ".array()" : ""}`;
    if (field.required !== false) expr += ".notNull()";
    if (field.unique) expr += ".unique()";
    if (field.defaultValue !== undefined) expr += `.default(${JSON.stringify(field.defaultValue)})`;
    if (field.references) {
      const r = field.references;
      if (!refs[r.model]) throw new Error(`Unknown reference ${r.model}`);
      expr += `.references(() => ${refs[r.model]}.${r.field}, { onDelete: ${JSON.stringify(r.onDelete ?? "cascade")} })`;
    }
    output += `  ${name}: ${expr},\n`;
  }
  const indexed = Object.entries(fields).filter(([, field]) => field.index && !field.unique);
  output += `}${indexed.length ? `, (t) => [${indexed.map(([name]) => `index(${JSON.stringify(`idx_hp_${snake(model)}_${snake(name)}`)}).on(t.${name})`).join(", ")}]` : ""}).enableRLS();\n\n`;
}
writeFileSync(new URL("../db/homepage-oauth-schema.ts", import.meta.url), output);
console.log(`Generated ${Object.keys(models).length} homepage OAuth tables; no database changes made.`);
